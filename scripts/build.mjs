/**
 * Build both halves of the plugin with the esbuild CLI.
 *
 * Some DSH shell sandboxes deny Node child processes that use piped stdio, so
 * the esbuild JavaScript API (which spawns its service over pipes) may fail.
 * The CLI binary is spawned with inherited stdio instead.
 *
 * Host half  → lib/index.js   (plain Node ESM; `@deepseek-ai/*` stays external)
 * Client half → lib/client.js (classic script wrapped in the ModuleLoader
 *               registration; the shell reads it with readFileSync)
 *
 *   node scripts/build.mjs
 */
import { existsSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { spawnSync } from 'node:child_process'

const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
if (typeof pkg.name !== 'string' || pkg.name === '') throw new Error('package.json has no name')

/** Candidate esbuild binaries, first existing wins. */
const ESBUILD_CANDIDATES = [
  process.env.ESBUILD_BINARY ?? '',
  'node_modules/.bin/esbuild',
  'node_modules/.bin/esbuild.exe',
  'node_modules/esbuild/bin/esbuild',
  '../dsh-aibrarian/node_modules/.pnpm/@esbuild+win32-x64@0.28.2/node_modules/@esbuild/win32-x64/esbuild.exe',
  '../dsh-zotero/node_modules/.pnpm/@esbuild+win32-x64@0.28.2/node_modules/@esbuild/win32-x64/esbuild.exe',
]

const esbuild = ESBUILD_CANDIDATES.find((candidate) => candidate !== '' && existsSync(candidate))
if (esbuild === undefined) {
  console.error('esbuild binary not found; set ESBUILD_BINARY to the esbuild executable path')
  process.exit(1)
}

/** Platform modules the shell seeds into the browser module table. */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const CLIENT_BANNER = `/**
 * ${pkg.name} — browser half (client bundle).
 *
 * Generated by scripts/build.mjs; edit src/client/** instead. The registration
 * id must equal the package name: it is the key the boot graph dispatches.
 */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkg.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
`

const CLIENT_FOOTER = `\t\treturn module.exports;
\t},
});
`

/** Run the esbuild CLI with inherited stdio; throws on a non-zero exit. */
function runEsbuild(args) {
  console.log(`$ esbuild ${args.join(' ')}`)
  const result = spawnSync(esbuild, args, { stdio: 'inherit', windowsHide: true })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) {
    console.error(`esbuild failed with exit code ${String(result.status)}`)
    process.exit(1)
  }
}

// Host half: plain Node ESM, DSH packages resolve at runtime through the profile.
runEsbuild([
  'src/index.ts',
  '--bundle',
  '--format=esm',
  '--platform=node',
  '--target=node22',
  '--sourcemap',
  '--external:@deepseek-ai/*',
  '--outfile=lib/index.js',
])

// Browser half: bundle to a body file, then wrap it in the ModuleLoader registration.
runEsbuild([
  'src/client/index.tsx',
  '--bundle',
  '--format=cjs',
  '--platform=browser',
  '--target=es2022',
  '--jsx=automatic',
  '--legal-comments=none',
  ...PLATFORM_MODULES.map((name) => `--external:${name}`),
  '--outfile=lib/client.body.js',
])

const body = readFileSync('lib/client.body.js', 'utf8')
writeFileSync('lib/client.js', `${CLIENT_BANNER}${body}${CLIENT_FOOTER}`)
rmSync('lib/client.body.js')

console.log('built lib/index.js and lib/client.js')
